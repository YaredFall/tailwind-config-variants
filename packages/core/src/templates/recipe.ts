import { camelCase, pascalCase } from "scule";
import { LIBRARY_NAME } from "../constant.ts";
import type { Recipe, SlotRecipe } from "../types";

export default function recipeTemplate({
    name,
    type,
    definition,
}: { name: string; type: "cva"; definition: Recipe } | { name: string; type: "sva"; definition: SlotRecipe }) {
    const variableName = camelCase(name);
    const typeName = pascalCase(`${name}Variants`);

    return `// Generated by ${LIBRARY_NAME}
import type { RecipeVariantProps } from "@tailwind-config-variants/core";
import { ${type} } from "../${type}";

const ${variableName} = ${type}(${JSON.stringify(definition, null, 4)});

export default ${variableName};
export type ${typeName} = RecipeVariantProps<typeof ${variableName}>;
`;
}
