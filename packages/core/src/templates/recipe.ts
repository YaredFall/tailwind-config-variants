import { pascalCase } from "scule";
import type { Recipe } from "../types";

export default function recipeTemplate(name: string, recipe: Recipe) {
    const typeName = pascalCase(`${name}Variants`);

    return `// Generated by tailwind-config-variants
import type { RecipeVariantProps } from "@tailwind-config-variants/core";
import { cva } from "../cva";

const ${name} = cva(${JSON.stringify(recipe, null, 4)});

export type ${typeName} = RecipeVariantProps<typeof ${name}>;

export default ${name};`;
}
