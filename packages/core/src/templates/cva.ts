import { LIBRARY_NAME } from "../constant.ts";

export default function cvaTemplate() {
    return `// Generated by ${LIBRARY_NAME}
import {
    type CVA,
    createSplitProps,
    getVariantKeys,
    getVariantMap,
    type Recipe,
    type VariantsDefinition,
} from "@tailwind-config-variants/core";
import { cx } from "./cx";

export function cva<V extends VariantsDefinition>({
    base,
    variants = {} as V,
    defaultVariants = {},
}: Recipe<V>): CVA<V> {
    const cva: CVA<V> = (variant = {}, ...className) => {
        const classNames = [base];
        for (const key in variants) {
            const variantValue = variant[key]?.toString();
            const defaultValue = defaultVariants[key]?.toString();
            if (variantValue) {
                classNames.push(variants[key][variantValue]);
            } else if (defaultValue) {
                classNames.push(variants[key][defaultValue]);
            }
        }

        return cx(...classNames, ...className);
    };

    cva.config = { base, variants, defaultVariants };
    cva.variantKeys = getVariantKeys(variants);
    cva.variantMap = getVariantMap(variants);
    cva.splitProps = createSplitProps(variants);

    return cva;
}`;
}
