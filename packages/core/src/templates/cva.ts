export default function cvaTemplate() {
    return `// Generated by tailwind-config-variants
import { cn, type ClassValue } from "./cn";

type BooleanStringToBoolean<T> = T extends "true" | "false" ? boolean : T;
type VariantMap = Record<string, Record<string, string>>;
type Variant<V extends VariantMap> = { [K in keyof V]?: BooleanStringToBoolean<keyof V[K]> };

export function cva<V extends VariantMap>({ 
    base, 
    variants, 
    defaultVariants
}: { 
    base: string; 
    variants: V; 
    defaultVariants: Variant<V>;
}) {
    return (variant: Variant<V> = {}, ...className: ClassValue[]) => {
        const classNames = [base];
        for (const key in variants) {
            const variantValue = variant[key]?.toString();
            const defaultValue = defaultVariants[key]?.toString();
            if (variantValue) {
                classNames.push(variants[key][variantValue]);
            } else if (defaultValue) {
                classNames.push(variants[key][defaultValue]);
            }
        }

        return cn(...classNames, ...className);
    };
}`;
}
