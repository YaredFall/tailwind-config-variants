export default function cvaTemplate() {
    return `// Generated by tailwind-config-variants
import type { VariantsMap, Variant, CVA } from "@tailwind-config-variants/core";
import { cn } from "./cn";

export function cva<V extends VariantsMap>({ 
    base, 
    variants, 
    defaultVariants
}: { 
    base: string; 
    variants: V; 
    defaultVariants: Variant<V>;
}): CVA<V> {
    const cvaFunction: CVA<V> = (variant= {}, ...className) => {
        const classNames = [base];
        for (const key in variants) {
            const variantValue = variant[key]?.toString();
            const defaultValue = defaultVariants[key]?.toString();
            if (variantValue) {
                classNames.push(variants[key][variantValue]);
            } else if (defaultValue) {
                classNames.push(variants[key][defaultValue]);
            }
        }

        return cn(...classNames, ...className);
    };
    
    cvaFunction.splitProps = (props) => {
        const variantProps = {} as typeof props;
        const otherProps = {} as typeof props;
        for (const key in props) {
            if (Object.hasOwn(variants, key)) variantProps[key] = props[key];
            else otherProps[key] = props[key];
        }
        return [variantProps, otherProps];
    };
    
    return cvaFunction;
}`;
}
