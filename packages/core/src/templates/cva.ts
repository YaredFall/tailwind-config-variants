export function cvaTemplate() {
    return `// Generated by tailwind-config-variants
import { cn } from "./cn";

type VariantMap = Record<string, Record<string, string>>;
type Variant<V extends VariantMap> = { [K in keyof V]?: keyof V[K] };

export function cva<V extends VariantMap>({ 
    base, 
    variants, 
    defaultVariants
}: { 
    base: string; 
    variants: V; 
    defaultVariants: Variant<V>;
}) {
    return (variant: Variant<V> = {}, className?: string) => {
        const classNames = [base];
        for (const key in variants) {
            const variantValue = variant[key];
            if (variantValue) {
                classNames.push(variants[key][variantValue]);
            } else if (defaultVariants[key]) {
                classNames.push(variants[key][defaultVariants[key]]);
            }
        }

        if (className) classNames.push(className);

        return cn(...classNames);
    };
}`;
}
